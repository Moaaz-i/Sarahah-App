import { OAuth2Client, CodeChallengeMethod } from 'google-auth-library';
import env from '../config/env.js';
import AppError from '../utils/AppError.js';
import { ERROR_CODES } from '../constants/messages.js';

/**
 * Thin wrapper around Google's official OAuth 2.0 / OIDC client.
 *
 * Responsibilities kept here (and nowhere else):
 * - Building the consent URL (state + PKCE challenge + nonce).
 * - Exchanging the authorization code server-side, always sending the
 *   EXACT redirect_uri that was configured in the environment.
 * - Verifying the ID token against Google's public keys, which also checks
 *   the signature, the issuer (`accounts.google.com`), the audience (our
 *   client id) and the expiry. We never trust claims sent by the browser.
 *
 * The real client is created lazily; tests inject a fake through
 * `setGoogleOidcClient()` so no test ever talks to Google.
 */

let injected = null;
let realClient = null;

const notConfiguredError = () =>
  new AppError(
    400,
    ERROR_CODES.OAUTH_NOT_CONFIGURED,
    'Google sign-in is not configured on this server',
  );

const buildRealClient = () => {
  if (!env.oauth.enabled) throw notConfiguredError();

  if (!realClient) {
    realClient = new OAuth2Client({
      clientId: env.oauth.clientId,
      clientSecret: env.oauth.clientSecret,
      redirectUri: env.oauth.redirectUri,
    });
  }
  return realClient;
};

/** Active client: the injected fake in tests, the real one everywhere else. */
export const getClient = () => injected ?? buildRealClient();

/** Test hook: inject a fake Google client (or null to restore the real one). */
export const setGoogleOidcClient = (fake) => {
  injected = fake;
};

export const isConfigured = () => env.oauth.enabled;

/** PKCE (RFC 7636) pair, generated by Google's own crypto helper. */
export const generatePkce = async () => {
  const { codeVerifier, codeChallenge } = await getClient().generateCodeVerifierAsync();
  return { codeVerifier, codeChallenge };
};

/**
 * The consent screen URL.
 *
 * `redirect_uri` is taken from the environment only (via the client that was
 * constructed from env); it is NEVER read from the incoming request, which is
 * what prevents an open-redirect / authorization-code theft.
 */
export const buildAuthorizationUrl = ({ state, codeChallenge, nonce, loginHint, prompt }) => {
  const client = getClient();

  const resolvedPrompt = prompt !== undefined ? prompt : loginHint ? undefined : env.oauth.prompt;

  const url = client.generateAuthUrl({
    access_type: 'online',
    ...(resolvedPrompt ? { prompt: resolvedPrompt } : {}),
    scope: env.oauth.scopes,
    state,
    nonce,
    code_challenge: codeChallenge,
    code_challenge_method: CodeChallengeMethod.S256,
    ...(loginHint ? { login_hint: loginHint } : {}),
  });

  return url;
};

/** Exchange the authorization code. Always server-side, never from the client. */
export const exchangeCode = async ({ code, codeVerifier }) => {
  const client = getClient();

  try {
    const { tokens } = await client.getToken({
      code,
      codeVerifier,
      redirect_uri: env.oauth.redirectUri,
    });

    if (!tokens?.id_token) {
      throw new Error('Google returned no id_token');
    }
    return tokens;
  } catch (err) {
    if (err instanceof AppError) throw err;
    throw AppError.unauthenticated(
      'Could not exchange the authorization code with Google',
      ERROR_CODES.OAUTH_CODE_EXCHANGE_FAILED,
    );
  }
};

/**
 * Verify the ID token (signature, issuer, audience, expiry) and return the
 * claims. Anything that fails verification becomes a 401.
 */
export const verifyIdToken = async (idToken) => {
  const client = getClient();

  try {
    const ticket = await client.verifyIdToken({
      idToken,
      audience: env.oauth.clientId,
    });

    const payload = ticket.getPayload();
    if (!payload || !payload.sub) {
      throw new Error('Google returned an empty ID token payload');
    }
    return payload;
  } catch (err) {
    if (err instanceof AppError) throw err;
    throw AppError.unauthenticated(
      'Google ID token could not be verified',
      ERROR_CODES.OAUTH_ID_TOKEN_INVALID,
    );
  }
};

export default {
  isConfigured,
  getClient,
  setGoogleOidcClient,
  generatePkce,
  buildAuthorizationUrl,
  exchangeCode,
  verifyIdToken,
};
